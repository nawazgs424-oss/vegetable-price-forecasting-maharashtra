# 2. DECOMPOSITION & STATIONARITY TESTING
# ==============================================================================
def decompose_and_check_stationarity(ts, name="Commodity"):
    """
    Performs classical decomposition and tests stationarity via ADF Test.
    """
    print(f"\n--- Decomposition & Stationarity: {name} ---")

    # Seasonal Decomposition (52 weeks = 1 year period)
    decomp_add = seasonal_decompose(ts, model='additive', period=52)
    decomp_mult = seasonal_decompose(ts, model='multiplicative', period=52)
    print(f"Additive Residual Std Dev:       {decomp_add.resid.std():.2f}")
    print(f"Multiplicative Residual Std Dev: {decomp_mult.resid.std():.2f}")

    # Augmented Dickey-Fuller Test on Raw Series
    adf_raw = adfuller(ts.dropna())
    print(f"Raw Series ADF Statistic: {adf_raw[0]:.4f} (p-value: {adf_raw[1]:.4f}) -> "
          f"{'Stationary' if adf_raw[1] < 0.05 else 'Non-Stationary'}")

    # ADF Test on 1st Differenced Series
    ts_diff = ts.diff().dropna()
    adf_diff = adfuller(ts_diff)
    print(f"1st Diff ADF Statistic:   {adf_diff[0]:.4f} (p-value: {adf_diff[1]:.4f}) -> "
          f"{'Stationary' if adf_diff[1] < 0.05 else 'Non-Stationary'}")

    return ts_diff


