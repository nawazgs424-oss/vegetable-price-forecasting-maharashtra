# ==============================================================================
# STEP 2: DECOMPOSITION & STATIONARITY TESTING
# ==============================================================================
def analyze_stationarity(ts, name="Commodity"):
    print(f"\n--- Stationarity Test (ADF): {name} ---")

    # ADF Test on Raw Data
    adf_raw = adfuller(ts)
    print(f"Raw Series ADF Stat: {adf_raw[0]:.4f} | p-value: {adf_raw[1]:.4f} -> "
          f"{'Stationary' if adf_raw[1] < 0.05 else 'Non-Stationary (Needs Differencing)'}")

    # ADF Test on 1st Differenced Data
    ts_diff = ts.diff().dropna()
    adf_diff = adfuller(ts_diff)
    print(f"1st Diff ADF Stat:   {adf_diff[0]:.4f} | p-value: {adf_diff[1]:.4f} -> "
          f"{'Stationary' if adf_diff[1] < 0.05 else 'Non-Stationary'}")


# ==============================================================================
# STEP 3: MODEL FITTING & IN-SAMPLE EVALUATION
