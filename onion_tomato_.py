import pandas as pd
from statsmodels.tsa.stattools import adfuller, kpss

def check_stationarity(series, alpha=0.05):
    """
    Runs ADF and KPSS tests to assess time series stationarity.
    """
    print("--- 1. Augmented Dickey-Fuller (ADF) Test ---")
    # H0: Series has a unit root (Non-Stationary)
    adf_result = adfuller(series.dropna())
    adf_stat, adf_pvalue = adf_result[0], adf_result[1]
    print(f"ADF Statistic: {adf_stat:.4f}")
    print(f"ADF p-value:   {adf_pvalue:.4f}")
    is_adf_stationary = adf_pvalue < alpha
    print(f"Result: {'Stationary' if is_adf_stationary else 'Non-Stationary'}\n")

    print("--- 2. KPSS Test ---")
    # H0: Series is stationary (Stationary)
    kpss_result = kpss(series.dropna(), regression='c', nlags="auto")
    kpss_stat, kpss_pvalue = kpss_result[0], kpss_result[1]
    print(f"KPSS Statistic: {kpss_stat:.4f}")
    print(f"KPSS p-value:   {kpss_pvalue:.4f}")
    is_kpss_stationary = kpss_pvalue >= alpha
    print(f"Result: {'Stationary' if is_kpss_stationary else 'Non-Stationary'}\n")

