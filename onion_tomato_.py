"""Manual Mathematical Calculation from Scratch (Regression Models)"""

import numpy as np

def calculate_aic_bic(y_true, y_pred, num_params):
    """
    Calculates AIC and BIC from residuals under Gaussian error assumption.

    Parameters:
        y_true : Ground truth target values
        y_pred : Model predictions
        num_params (k) : Number of estimated parameters (features + intercept + variance)
    """
    n = len(y_true)
    residuals = y_true - y_pred
    mse = np.mean(residuals ** 2)

    # Residual Sum of Squares / Likelihood approximation
    aic = n * np.log(mse) + 2 * num_params
    bic = n * np.log(mse) + num_params * np.log(n)

    return aic, bic

# Example Usage:
y_actual = np.array([1200, 1250, 1100, 1300, 1400])
y_predicted = np.array([1190, 1240, 1120, 1290, 1380])
k = 3 # 2 features + intercept

aic, bic = calculate_aic_bic(y_actual, y_predicted, num_params=k)
print(f"Calculated AIC: {aic:.4f}")
print(f"Calculated BIC: {bic:.4f}")

