"""2. Deep Learning Sequence Forecasting (LSTM PyTorch)

An LSTM network architecture using historical 30-day sequence windows to predict future prices.
"""

import torch
import torch.nn as nn
import pandas as pd
import numpy as np
from sklearn.preprocessing import MinMaxScaler

# 1. Prepare Data
df = pd.read_csv('agmarknet_maharashtra_onion_tomato_fit_ready_daily_timeseries_2010_2026.csv')
price_series = df[df['commodity'] == 'Tomato'].sort_values('date')['modal_price_arrival_weighted_rs_per_quintal'].dropna().values.reshape(-1, 1)

scaler = MinMaxScaler()
scaled_data = scaler.fit_transform(price_series)

def create_sequences(data, seq_length=30):
    xs, ys = [], []
    for i in range(len(data) - seq_length):
        xs.append(data[i:i + seq_length])
        ys.append(data[i + seq_length])
    return torch.tensor(np.array(xs), dtype=torch.float32), torch.tensor(np.array(ys), dtype=torch.float32)

X, y = create_sequences(scaled_data, seq_length=30)
train_size = int(len(X) * 0.8)
X_train, y_train = X[:train_size], y[:train_size]

# 2. LSTM Architecture
class PriceLSTM(nn.Module):
    def __init__(self, input_size=1, hidden_size=64, num_layers=2):
        super().__init__()
        self.lstm = nn.LSTM(input_size, hidden_size, num_layers, batch_first=True)
        self.fc = nn.Linear(hidden_size, 1)

    def forward(self, x):
        out, _ = self.lstm(x)
        return self.fc(out[:, -1, :])

model = PriceLSTM()
criterion = nn.MSELoss()
optimizer = torch.optim.Adam(model.parameters(), lr=0.001)

# 3. Model Training
epochs = 20
for epoch in range(epochs):
    model.train()
    optimizer.zero_grad()
    outputs = model(X_train)
    loss = criterion(outputs, y_train)
    loss.backward()
    optimizer.step()
    if (epoch + 1) % 5 == 0:
        print(f"Epoch [{epoch+1}/{epochs}], Loss: {loss.item():.6f}")

