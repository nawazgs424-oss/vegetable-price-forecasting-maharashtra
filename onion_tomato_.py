"""Residual & Error Metrics (MAE, MSE, RMSE, MAPE)

Functions to compute standard forecast error metrics on time series models.
"""

import numpy as np
import pandas as pd
from sklearn.metrics import mean_absolute_error, mean_squared_error

def evaluate_forecast_errors(y_true, y_pred):
    """
    Computes key time-series forecasting error metrics.
    """
    y_true, y_pred = np.array(y_true), np.array(y_pred)

    mae = mean_absolute_error(y_true, y_pred)
    mse = mean_squared_error(y_true, y_pred)
    rmse = np.sqrt(mse)
    mape = np.mean(np.abs((y_true - y_pred) / y_true)) * 100

    metrics = {
        'MAE': mae,
        'MSE': mse,
        'RMSE': rmse,
        'MAPE (%)': mape
    }
    return pd.Series(metrics)

# Example Usage:
y_actual = [1200, 1250, 1100, 1300, 1400]
y_forecast = [1180, 1260, 1120, 1280, 1370]

