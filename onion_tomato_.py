def fit_sarimax(ts, order=(1, 1, 1), seasonal_order=(1, 0, 1, 52)):
    model = SARIMAX(ts,
                    order=order,
                    seasonal_order=seasonal_order,
                    enforce_stationarity=False,
                    enforce_invertibility=False)
    return model.fit(disp=False)

def compute_metrics(actual, pred, label="Model"):
    rmse = np.sqrt(mean_squared_error(actual, pred))
    mae = mean_absolute_error(actual, pred)
    mape = mean_absolute_percentage_error(actual, pred) * 100

    ss_res = np.sum((actual - pred)**2)
    ss_tot = np.sum((actual - np.mean(actual))**2)
    r2 = 1 - (ss_res / ss_tot)

    return {
        'Model': label,
        'RMSE (₹)': round(rmse, 2),
        'MAE (₹)': round(mae, 2),
        'MAPE (%)': round(mape, 2),
        'R² Score': round(r2, 4)
    }


# ==============================================================================
# STEP 4: RESIDUAL DIAGNOSTICS & NORMALITY TESTS
# ==============================================================================
def evaluate_residuals(fitted_model, label="Model"):
    residuals = fitted_model.resid.iloc[1:]

    # White Noise Test
    lb_pvalue = acorr_ljungbox(residuals, lags=[10])['lb_pvalue'].values[0]

    # Normality Tests
    sw_stat, sw_pvalue = stats.shapiro(residuals)
    jb_stat, jb_pvalue, skew, kurt = jarque_bera(residuals)

    return {
        'Model': label,
        'Mean Residual': round(residuals.mean(), 4),
        'Skewness': round(skew, 4),
        'Kurtosis': round(kurt, 4),
        'Ljung-Box p-val': round(lb_pvalue, 4),
        'Shapiro p-val': round(sw_pvalue, 4),
        'Jarque-Bera p-val': round(jb_pvalue, 4)
    }


# ==============================================================================
# STEP 5: OUT-OF-SAMPLE EVALUATION (80/20 SPLIT)
# ==============================================================================
def evaluate_out_of_sample(ts, order=(1, 1, 1), seasonal_order=(1, 0, 1, 52), label="Commodity"):
    train_size = int(len(ts) * 0.80)
    train, test = ts.iloc[:train_size], ts.iloc[train_size:]

    fit_oos = SARIMAX(train, order=order, seasonal_order=seasonal_order,
                      enforce_stationarity=False, enforce_invertibility=False).fit(disp=False)

    pred_oos = fit_oos.forecast(steps=len(test))
    return compute_metrics(test, pred_oos, f"{label} Out-of-Sample")


