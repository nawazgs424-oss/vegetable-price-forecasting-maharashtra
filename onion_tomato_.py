# 3. MODEL FITTING & IN-SAMPLE EVALUATION
# ==============================================================================
def fit_sarimax_model(ts, order=(1, 1, 1), seasonal_order=(1, 0, 1, 52)):
    """
    Fits Seasonal ARIMA (SARIMAX) model on the given time series.
    """
    model = SARIMAX(ts,
                    order=order,
                    seasonal_order=seasonal_order,
                    enforce_stationarity=False,
                    enforce_invertibility=False)
    fitted_model = model.fit(disp=False)
    return fitted_model

def evaluate_in_sample_performance(ts_actual, fitted_model, label="Model"):
    """
    Computes in-sample accuracy metrics (RMSE, MAE, MAPE, R^2).
    """
    actual = ts_actual.iloc[1:]
    pred = fitted_model.fittedvalues.iloc[1:]

    rmse = np.sqrt(mean_squared_error(actual, pred))
    mae = mean_absolute_error(actual, pred)
    mape = mean_absolute_percentage_error(actual, pred) * 100
    r2 = 1 - (np.sum((actual - pred)**2) / np.sum((actual - actual.mean())**2))

    metrics = {
        'Model': label,
        'RMSE': round(rmse, 2),
        'MAE': round(mae, 2),
        'MAPE (%)': round(mape, 2),
        'R² Score': round(r2, 4)
    }
    return metrics


# ==============================================================================
# 4. RESIDUAL DIAGNOSTICS & NORMALITY TESTS
# ==============================================================================
def evaluate_residual_diagnostics(fitted_model, label="Model"):
    """
    Runs Ljung-Box test for White Noise and Shapiro-Wilk / Jarque-Bera for Normality.
    """
    residuals = fitted_model.resid.iloc[1:]

    # White Noise Test
    lb_test = acorr_ljungbox(residuals, lags=[10], return_df=True)
    lb_pvalue = lb_test['lb_pvalue'].values[0]

    # Normality Tests
    sw_stat, sw_pvalue = stats.shapiro(residuals)
    jb_stat, jb_pvalue, skew, kurt = jarque_bera(residuals)

    diag_summary = {
        'Model': label,
        'Mean Residual': round(residuals.mean(), 4),
        'Skewness': round(skew, 4),
        'Kurtosis': round(kurt, 4),
        'Ljung-Box p-val': round(lb_pvalue, 4),
        'Shapiro p-val': round(sw_pvalue, 4),
        'Jarque-Bera p-val': round(jb_pvalue, 4)
    }
    return diag_summary


